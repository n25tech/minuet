import { createHash } from 'node:crypto';
import { cp, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { build } from 'esbuild';

// The browser's DOM-free logic is also what the server uses to apply the scheduling rules,
// so the two can't drift apart. The browser loads these as plain scripts; the server needs a module.
export const CORE_SOURCES = ['js/calendar-core.js', 'js/tasks-core.js'];
export const CORE_MODULE = 'functions/api/_lib/core.js';
const CORE_EXPORTS = [
    'DAY_MS', 'toYMD', 'toHM', 'toLocalISO', 'parseLocal', 'startOfDay', 'addDays', 'daysBetween', 'eventBounds',
    'REPEAT_FREQS', 'expandEvents', 'resolveSchedule',
    'POMODORO_LABEL', 'TODO_NOTE_ID', 'DIARY_NOTE_ID', 'isDefaultNote', 'newDefaultNote', 'hasPomodoroLabel', 'pomodoroNotes', 'legacyTodoItems',
    'clearTask', 'setRepeat', 'setStatus', 'noteHeading', 'noteTasks', 'settleTasks',
];

// Browser bundles of npm libraries (and the code using them), for the app's plain scripts.
// index.html refers to each as js/<name>.js; the built page points at bundles/<name>-<hash>.js, so a
// changed bundle gets a new address and browsers never keep a stale copy (_headers lets them cache
// bundles/ for good). They are ES modules so parts used now and then (code colouring) load on demand.
export const BUNDLES = { markdown: 'src/markdown/browser.js' };

async function buildBundles() {
    let html = await readFile('public/index.html', 'utf8');
    for (const [name, entry] of Object.entries(BUNDLES)) {
        const result = await build({
            entryPoints: { [name]: entry },
            bundle: true,
            format: 'esm',
            splitting: true,
            minify: true,
            target: 'es2020',
            outdir: 'public/bundles',
            entryNames: '[name]-[hash]',
            chunkNames: '[name]-[hash]',
            metafile: true,
            legalComments: 'linked',
            logLevel: 'warning',
        });
        const [output] = Object.entries(result.metafile.outputs).find(([, info]) => info.entryPoint === entry);
        const reference = `<script type="module" src="js/${name}.js">`;
        if (!html.includes(reference)) throw new Error(`index.html has no ${reference} for the ${name} bundle`);
        html = html.replace(reference, `<script type="module" src="${output.replace(/^public\//, '')}">`);
    }
    await writeFile('public/index.html', html);
}

/*
 * The deployed version: a hash of every built file's path and contents, so it changes exactly when
 * something a browser loads changes. It goes into the page (<meta name="minuet-version">) and into
 * version.json, which js/update.js compares to offer a refresh after a deploy.
 */
export function versionOf(files) {
    const hash = createHash('sha256');
    for (const [path, contents] of [...files].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
        hash.update(path).update('\0').update(contents).update('\0');
    }
    return hash.digest('hex').slice(0, 12);
}

export function stampVersion(html, version) {
    const charset = '<meta charset="UTF-8">';
    if (!html.includes(charset)) throw new Error(`index.html has no ${charset} to put the version after`);
    return html.replace(charset, `${charset}\n  <meta name="minuet-version" content="${version}">`);
}

async function builtFiles(dir, prefix = '') {
    const files = [];
    for (const entry of await readdir(dir, { withFileTypes: true })) {
        const path = `${prefix}${entry.name}`;
        if (entry.isDirectory()) files.push(...await builtFiles(`${dir}/${entry.name}`, `${path}/`));
        else if (path !== 'version.json') files.push([path, await readFile(`${dir}/${entry.name}`)]);
    }
    return files;
}

async function writeVersion() {
    const version = versionOf(await builtFiles('public'));
    const html = await readFile('public/index.html', 'utf8');
    await writeFile('public/index.html', stampVersion(html, version));
    await writeFile('public/version.json', JSON.stringify({ version }) + '\n');
}

export async function coreModuleSource() {
    const parts = await Promise.all(CORE_SOURCES.map(path => readFile(path, 'utf8')));
    return `// GENERATED by scripts/build.js from ${CORE_SOURCES.join(' and ')} - do not edit; run "npm run build".\n\n`
        + parts.join('\n') + `\nexport {\n    ${CORE_EXPORTS.join(', ')},\n};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
    await mkdir('functions/api/_lib', { recursive: true });
    await writeFile(CORE_MODULE, await coreModuleSource());

    await rm('public', { recursive: true, force: true });
    await mkdir('public');
    for (const path of ['index.html', 'js', 'assets', 'sw.js', '_headers', 'manifest.webmanifest']) {
        await cp(path, `public/${path}`, { recursive: true });
    }
    await buildBundles();
    await writeVersion();
}
